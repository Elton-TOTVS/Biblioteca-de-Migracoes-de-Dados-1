IF OBJECT_ID('ZDEPARA_GRUPO_OCORRENCIA_COMPL') IS NOT NULL
  DROP TABLE ZDEPARA_GRUPO_OCORRENCIA_COMPL ; 

SELECT 
      CODIGO                  AS CODIGO,
      COD_EXT                 AS COD_EXT,
      DESCRICAO               AS DESCICAO,
      NOTIFICAR               AS NOTIFICAR,
      FREQUENCIA              AS FREQUENCIA,
      INTERNA                 AS INTERNA,
      ''                      AS CODIGO_PARA,
      ''                      AS DESCRICAO_PARA
      INTO ZDEPARA_GRUPO_OCORRENCIA_COMPL
  FROM 
      SOPHIA.OCORRENCIAS
 WHERE
      NOT EXISTS (SELECT 1 FROM ZDEPARA_GRUPO_OCORRENCIA AS Z WHERE Z.CODIGO = SOPHIA.OCORRENCIAS.CODIGO AND Z.COD_EXT = SOPHIA.OCORRENCIAS.COD_EXT AND Z.DESCICAO = SOPHIA.OCORRENCIAS.DESCRICAO)      ;

SELECT * FROM ZDEPARA_GRUPO_OCORRENCIA_COMPL ;