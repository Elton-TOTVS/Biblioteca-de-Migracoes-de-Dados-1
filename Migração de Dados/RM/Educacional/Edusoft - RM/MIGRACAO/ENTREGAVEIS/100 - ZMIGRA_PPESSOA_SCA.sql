		   ISNULL(PPESSOA_ALUNOS.ESTELEIT,'') AS ESTELEIT,
		   ISNULL(CAST(PPESSOA_ALUNOS.CARTEIRATRAB AS VARCHAR),'') AS CARTEIRATRAB,
		   ISNULL(PPESSOA_ALUNOS.SERIECARTTRAB,'') AS SERIECARTTRAB,
		   ISNULL(PPESSOA_ALUNOS.UFCARTTRAB,'') AS UFCARTTRAB,
		   PPESSOA_ALUNOS.DTCARTTRAB,
		   '' AS NIT,
		   ISNULL(PPESSOA_ALUNOS.CARTMOTORISTA,'') AS CARTMOTORISTA,
		   ISNULL(PPESSOA_ALUNOS.TIPOCARTHABILIT,'') AS TIPOCARTHABILIT,
		   PPESSOA_ALUNOS.DTVENCHABILIT,
		   ISNULL(PPESSOA_ALUNOS.SITMILITAR,'') AS SITMILITAR,
		   ISNULL(PPESSOA_ALUNOS.CERTIFRESERV,'') AS CERTIFRESERV,
		   ISNULL(PPESSOA_ALUNOS.CATEGMILITAR,'') AS CATEGMILITAR,
		   ISNULL(PPESSOA_ALUNOS.CSM,'') AS CSM,
		   PPESSOA_ALUNOS.DTEXPCML,
		   ISNULL(PPESSOA_ALUNOS.EXPED,'') AS EXPED,
		   ISNULL(PPESSOA_ALUNOS.RM,'') AS RM,
