		   ISNULL(CAST(PPESSOA_ALUNOS.TELEFONE3 AS VARCHAR),'') AS TELEFONE3,
		   ISNULL(PPESSOA_ALUNOS.FAX,'') AS FAX,
		   ISNULL(PPESSOA_ALUNOS.EMAIL,'') AS EMAIL,
		   ISNULL(PPESSOA_ALUNOS.CARTIDENTIDADE,'') AS CARTIDENTIDADE,
		   ISNULL(PPESSOA_ALUNOS.UFCARTIDENT,'') AS UFCARTIDENT,
		   ISNULL(PPESSOA_ALUNOS.ORGEMISSORIDENT,'') AS ORGEMISSORIDENT,
		   PPESSOA_ALUNOS.DTEMISSAOIDENT,
