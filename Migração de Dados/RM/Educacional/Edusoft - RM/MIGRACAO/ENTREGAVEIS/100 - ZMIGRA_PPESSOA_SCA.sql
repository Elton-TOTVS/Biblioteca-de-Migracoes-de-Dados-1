		   ISNULL(PPESSOA_ALUNOS.TIPOSANG,'') AS TIPOSANG,
		   PPESSOA_ALUNOS.ALUNO,
		   PPESSOA_ALUNOS.PROFESSOR,
		   PPESSOA_ALUNOS.USUARIOBIBLIOS,
		   PPESSOA_ALUNOS.FUNCIONARIO,
		   PPESSOA_ALUNOS.EXFUNCIONARIO,
		   PPESSOA_ALUNOS.CANDIDATO,
		   PPESSOA_ALUNOS.FALECIDO,
		   PPESSOA_ALUNOS.DATAOBITO,
		   ISNULL(PPESSOA_ALUNOS.MATRICULAOBITO,'') AS MATRICULAOBITO,
		   ISNULL(PPESSOA_ALUNOS.NOMESOCIAL,'') AS NOMESOCIAL
      FROM PPESSOA_ALUNOS) PESSOAS
  WHERE RN = 1
    AND NOT EXISTS (SELECT 1
				      FROM SESC_SOPHIA_MG_HMG2.dbo.ZPESSOA
				     WHERE ZPESSOA.CPF COLLATE Latin1_General_CI_AI = PESSOAS.CPF COLLATE Latin1_General_CI_AI)
    AND NOT EXISTS (SELECT 1
					  FROM SESC_SOPHIA_MG_HMG2.dbo.ZDADOSORIGEM
					 WHERE ZDADOSORIGEM.CPF COLLATE Latin1_General_CI_AI = PESSOAS.CPF COLLATE Latin1_General_CI_AI)

