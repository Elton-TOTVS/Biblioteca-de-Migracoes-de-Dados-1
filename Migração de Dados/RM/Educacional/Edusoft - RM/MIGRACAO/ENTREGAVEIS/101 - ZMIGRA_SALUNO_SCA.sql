IF OBJECT_ID('ZMIGRA_SALUNO') IS NOT NULL
	DROP TABLE ZMIGRA_SALUNO;

SELECT ALUNOS.* INTO ZMIGRA_SALUNO FROM (
SELECT ROW_NUMBER() OVER (PARTITION BY ALUNOS.CPF ORDER BY ALUNOS.NOME) AS RN,
	   ALUNOS.NOME,
	   ALUNOS.SOBRENOME,
	   CAST(ALUNOS.DTNASCIMENTO AS VARCHAR(10)) AS DTNASCIMENTO,
	   ALUNOS.CPF,
	   ISNULL(ALUNOS.CARTIDENTIDADE,'') AS CARTIDENTIDADE,
	   ISNULL(ALUNOS.UFCARTIDENT,'') AS UFCARTIDENT,
	   ISNULL(ALUNOS.CARTEIRATRAB,'') AS CARTEIRATRAB,
	   ISNULL(ALUNOS.SERIECARTTRAB,'') AS SERIECARTTRAB,
	   ISNULL(ALUNOS.UFCARTTRAB,'') AS UFCARTTRAB,
	   ISNULL(ALUNOS.EMPRESANOME,'') AS EMPRESANOME,
	   ISNULL(ALUNOS.EMPRESARUA,'') AS EMPRESARUA,
	   ISNULL(ALUNOS.EMPRESANUMERO,'') AS EMPRESANUMERO,
	   ISNULL(ALUNOS.EMPRESACOMPLEMENTO,'') AS EMPRESACOMPLEMENTO,
	   ISNULL(ALUNOS.EMPRESABAIRRO,'') AS EMPRESABAIRRO,
	   ISNULL(ALUNOS.EMPRESACEP,'') AS EMPRESACEP,
	   ISNULL(ALUNOS.EMPRESACIDADE,'') AS EMPRESACIDADE,
	   ISNULL(ALUNOS.EMPRESAUF,'') AS EMPRESAUF,
	   ISNULL(ALUNOS.EMPRESATELEFONE,'') AS EMPRESATELEFONE,
	   ISNULL(ALUNOS.EMPRESAHORARIO,'') AS EMPRESAHORARIO,
	   ISNULL(ALUNOS.TIPOCERTIDAO,'') AS TIPOCERTIDAO,
	   ISNULL(ALUNOS.CERTNUMERO,'') AS CERTNUMERO,
	   ISNULL(ALUNOS.CERTCARTORIO,'') AS CERTCARTORIO,
	   ISNULL(CAST(ALUNOS.CERTCOMARCA AS VARCHAR),'') AS CERTCOMARCA,
	   CAST(ALUNOS.CERTDATA AS VARCHAR(10)) AS CERTDATA,
	   ISNULL(ALUNOS.CERTFOLHA,'') AS CERTFOLHA,
	   ISNULL(ALUNOS.CERTLIVRO,'') AS CERTLIVRO,
	   ISNULL(ALUNOS.CERTDISTRITO,'') AS CERTDISTRITO,
	   ISNULL(ALUNOS.CERTUF,'') AS CERTUF,
	   ISNULL(ALUNOS.NOMEPAI,'') AS NOMEPAI,
	   CAST(ALUNOS.DTNASCIMENTOPAI AS VARCHAR(10)) AS DTNASCIMENTOPAI,
	   ISNULL(ALUNOS.CPFPAI,'') AS CPFPAI,
	   ISNULL(ALUNOS.RGPAI,'') AS RGPAI,
	   ISNULL(ALUNOS.NOMEMAE,'') AS NOMEMAE,
	   CAST(ALUNOS.DTNASCIMENTOMAE AS VARCHAR(10)) AS DTNASCIMENTOMAE,
	   ISNULL(ALUNOS.CPFMAE,'') AS CPFMAE,
	   ISNULL(ALUNOS.RGMAE,'') AS RGMAE,
	   ISNULL(ALUNOS.CODCOLIGADA,'14') AS CODCOLIGADA,
	   FORMAT(6969570+ROW_NUMBER() OVER (ORDER BY ALUNOS.RA) , '00000000') + -- '-'+ - RETIRANDO O "-" DO CÓDIGO DA MATRÍCULA
	   CAST(dbo.fn_calcular_digito_verificador_modulo10(6969570+ROW_NUMBER() OVER (ORDER BY ALUNOS.RA) ) AS VARCHAR(1)) AS RA,
	   ISNULL(ALUNOS.TIPOALUNO,'') AS TIPOALUNO,
	   ISNULL(ALUNOS.INSTDESTINO,'') AS INSTDESTINO,
	   ISNULL(ALUNOS.INSTORIGEM,'') AS INSTORIGEM,
	   ISNULL(ALUNOS.CODCURHIST,'') AS CODCURHIST,
	   ISNULL(ALUNOS.CODSERIEHIST,'') AS CODSERIEHIST,
	   ISNULL(ALUNOS.CODCOLCFO,'') AS CODCOLCFO,
	   ISNULL(ALUNOS.CODCFO,'') AS CODCFO,
	   ISNULL(ALUNOS.CODPARENTCFO,'') AS CODPARENTCFO,
	   ISNULL(ALUNOS.NOMERESPACAD,'') AS NOMERESPACAD,
	   CAST(ALUNOS.DTNASCIMENTORESPACAD AS VARCHAR(10)) AS DTNASCIMENTORESPACAD,
	   ISNULL(ALUNOS.CPFRESPACAD,'') AS CPFRESPACAD,
	   ISNULL(ALUNOS.RGRESPACAD,'') AS RGRESPACAD,
	   ISNULL(ALUNOS.CODPARENTRACA,'') AS CODPARENTRACA,
	   ISNULL(ALUNOS.OBSHIST,'') AS OBSHIST,
	   ISNULL(ALUNOS.IDENTIFICADOR2,'') AS IDENTIFICADOR2,
	   ISNULL(ALUNOS.IDENTIFICADOR3,'') AS IDENTIFICADOR3,
	   ISNULL(ALUNOS.ANOINGRESSO,'') AS ANOINGRESSO,
	   ISNULL(ALUNOS.ANOTACOES,'') AS ANOTACOES,
	   ISNULL(ALUNOS.CODTIPOCURSO,'') AS CODTIPOCURSO,
	   ISNULL(ALUNOS.CODINSTORIGEM,'') AS CODINSTORIGEM,
	   ISNULL(ALUNOS.CODINSTDESTINO,'') AS CODINSTDESTINO,	   
	   ISNULL(ALUNOS.NATURALIDADE,'') AS NATURALIDADE,
	   ISNULL(ALUNOS.ESTADONATAL,'') AS ESTADONATAL,
	   ISNULL(CAST(ALUNOS.NATURALIDADEPAI AS VARCHAR),'') AS NATURALIDADEPAI,
	   ISNULL(ALUNOS.ESTADONATALPAI,'') AS ESTADONATALPAI,
	   ISNULL(ALUNOS.NATURALIDADEMAE,'') AS NATURALIDADEMAE,
	   ISNULL(ALUNOS.ESTADONATALMAE,'') AS ESTADONATALMAE,
	   'NÃO IDENTIFICADO' AS NATURALIDADEACAD,
	   '' AS ESTADONATALACAD,
	   ISNULL(ALUNOS.CODSISTEC,'') AS CODSISTEC,
	   ISNULL(ALUNOS.CODINST2GRAU,'') AS CODINST2GRAU,
	   ISNULL(ALUNOS.GRAUULTIMAINST,'') AS GRAUULTIMAINST,
	   ISNULL(ALUNOS.ANOULTIMAINST,'') AS ANOULTIMAINST,
	   ISNULL(ALUNOS.CODETNIA,'') AS CODETNIA
  FROM ALUNOS) ALUNOS
 WHERE RN = 1;

ALTER TABLE ZMIGRA_SALUNO DROP COLUMN RN;

SELECT * FROM ZMIGRA_SALUNO;