IF OBJECT_ID('ZDEPARA_COLIGADAS') IS NOT NULL 
   DROP TABLE ZDEPARA_COLIGADAS;
SELECT DADOS.*
       INTO ZDEPARA_COLIGADAS
FROM (		 
SELECT DISTINCT 
	   DENSE_RANK() OVER(ORDER BY CASE WHEN EMP.CNPJBASE = '05603629' THEN '05.603.629/0001-40' -- LCS
									   WHEN EMP.CNPJBASE = '17027472' THEN '17.027.472/0001-30' -- LC
									   WHEN EMP.CNPJBASE = '48636176' THEN '48.636.176/0001-60' -- PATIO
									   WHEN EMP.CNPJBASE = '11465561' THEN '11.465.561/0001-82' -- PET	
									   WHEN EMP.CNPJBASE = '05525104' THEN '05.525.104/0001-33' -- ATIVA
									   WHEN EMP.CNPJBASE = '60538885' THEN '60.538.885/0001-09' -- MCCOFFE
								  END ) AS ID,							
	   
	   ISNULL(EPG.EMP_CODIGO, EMP.CODIGO) AS EMPRESA_DE,
       EMP.Nome AS NOME_DE,
	   EMP.RAZAOSOCIAL,	
	   CASE 
		   WHEN EMP.CNPJBASE = '05603629' THEN '05.603.629/0001-40' -- LCS
           WHEN EMP.CNPJBASE = '17027472' THEN '17.027.472/0001-30' -- LC
           WHEN EMP.CNPJBASE = '48636176' THEN '48.636.176/0001-60' -- PATIO
           WHEN EMP.CNPJBASE = '11465561' THEN '11.465.561/0001-82' -- PET
           WHEN EMP.CNPJBASE = '05525104' THEN '05.525.104/0001-33' -- ATIVA
           WHEN EMP.CNPJBASE = '60538885' THEN '60.538.885/0001-09' -- MCCOFFE
	    END AS CNPJ,
	   EMP.DESATIVADA,
	   
	   ISNULL(SUM(CASE WHEN EPG.DTRESCISAO IS NULL AND EPG.NOME IS NOT NULL THEN 1 ELSE 0 END), 0) AS ATIVOS,
       ISNULL(SUM(CASE WHEN EPG.DTRESCISAO IS NOT NULL AND EPG.NOME IS NOT NULL THEN 1 ELSE 0 END), 0) AS INATIVOS, 
       ISNULL(SUM(CASE WHEN EPG.NOME IS NOT NULL THEN 1 ELSE 0 END), 0) AS TOTAL,
	   
	   CASE 
		   WHEN EMP.CNPJBASE = '05603629' THEN 1 -- LCS
           WHEN EMP.CNPJBASE = '17027472' THEN 2 -- LC
           WHEN EMP.CNPJBASE = '48636176' THEN 3 -- PATIO
           WHEN EMP.CNPJBASE = '11465561' THEN 4 -- PET
           WHEN EMP.CNPJBASE = '05525104' THEN 5 -- ATIVA
           WHEN EMP.CNPJBASE = '60538885' THEN 6 -- MCCOFFE
	   END AS CODCOLIGADA,
	   1 AS FILIAL_PARA

  FROM EMP  
  LEFT JOIN EPG ON EMP.CODIGO = EPG.EMP_CODIGO 
 WHERE EMP.CNPJBASE IN (
						'05603629',
						'17027472',
						'48636176',
						'11465561',
						'05525104',
						'60538885')
-- AND SUM(CASE WHEN EPG.DTRESCISAO IS NULL AND EPG.NOME IS NOT NULL THEN 1 ELSE 0 END) >=1
 GROUP BY 
       EPG.EMP_CODIGO,
	   EMP.CODIGO,
	   EMP.NOME,
	   EMP.RAZAOSOCIAL,
	   EMP.NMFANTASIA,
	   EMP.CNPJBASE,
	   EMP.CPF,
	   EMP.DESATIVADA) AS DADOS 
WHERE DADOS.INATIVOS >=1 
	AND DADOS.DESATIVADA <> 1;

SELECT * FROM ZDEPARA_COLIGADAS 
ORDER BY CODCOLIGADA;